const fold = (s) => s.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase();

export function filterTracks(tracks, query) {
  const q = fold(query.trim());
  if (!q) return tracks;
  return tracks.filter((t) => fold(t.title).includes(q) || fold(t.artist).includes(q));
}

// Spotify keeps isPaused false when a track (or 30s preview) runs out, so the end counts as stopped.
export function isPlaying({ isPaused, position, duration }) {
  return !isPaused && !(duration > 0 && position >= duration - 250);
}

export function formatTime(ms) {
  const s = Math.floor((ms || 0) / 1000);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

// The track before/after `id`, wrapping at the ends; shuffle picks any other track.
export function stepTrack(tracks, id, dir, shuffle = false, rand = Math.random) {
  if (shuffle) {
    const others = tracks.filter((t) => t.id !== id);
    if (others.length) return others[Math.floor(rand() * others.length)];
  }
  const i = tracks.findIndex((t) => t.id === id);
  return tracks[(i + dir + tracks.length) % tracks.length];
}

const IFRAME_API = "https://open.spotify.com/embed/iframe-api/v1";

// Spotify's own embed controller runs hidden; the bar below the list is the visible player.
// Created the first time Music opens so nothing loads before that.
export function initMusic(root, { onPlayingChange, onNow } = {}) {
  const search = root.querySelector(".music__search");
  const empty = root.querySelector(".music__empty");
  const host = root.querySelector("[data-player]");
  const links = [...root.querySelectorAll("a[data-track-id]")];
  const now = root.querySelector(".music__now");
  const $ = (s) => now.querySelector(s);
  const [art, name, artist, playBtn, seek, timeNow, timeEnd] = [
    ".music__now-art", ".music__now-title", ".music__now-artist", ".music__pp", ".music__seek", ".music__t-now", ".music__t-end",
  ].map($);
  const [shuffleBtn, prevBtn, nextBtn, repeatBtn] = ["shuffle", "prev", "next", "repeat"].map((k) => $(`[data-ctl="${k}"]`));
  let controller = null;
  let ready = false; // script loaded; until then track links just open Spotify
  let wanted = null; // a track asked for before the controller existed
  let playOnLoad = false;
  let current = null;
  let ended = true; // true until a fresh update shows the new track is under way, so a stale "end" can't skip twice
  let quiet = 0; // updates arrive about once a second while playing; silence means it stopped

  const visible = () => filterTracks(TRACKS, search.value);

  search.addEventListener("input", () => {
    const keep = new Set(visible().map((t) => t.id));
    links.forEach((a) => { a.parentElement.hidden = !keep.has(a.dataset.trackId); });
    empty.hidden = keep.size > 0;
    empty.textContent = keep.size ? "" : `No songs match "${search.value.trim()}"`;
  });

  function setPlaying(playing) {
    root.classList.toggle("is-playing", playing);
    playBtn.setAttribute("aria-label", playing ? "Pause" : "Play");
    onPlayingChange?.(playing);
  }

  function play(track) {
    current = track;
    links.forEach((l) => l.toggleAttribute("aria-current", l.dataset.trackId === track.id));
    art.src = artUrl(track.art, 300);
    now.style.setProperty("--cover", `url(${art.src})`);
    name.textContent = track.title;
    name.href = `https://open.spotify.com/track/${track.id}`;
    artist.textContent = track.artist;
    seek.value = 0;
    seek.style.setProperty("--pos", "0%");
    timeNow.textContent = "0:00";
    now.hidden = false;
    onNow?.({ track, position: 0, duration: 0 });
    const uri = `spotify:track:${track.id}`;
    if (!controller) { wanted = track; return; }
    playOnLoad = true;
    controller.loadUri(uri);
  }

  const step = (dir) => current && play(stepTrack(visible(), current.id, dir, shuffleBtn.getAttribute("aria-pressed") === "true"));

  root.addEventListener("click", (e) => {
    const a = e.target.closest("a[data-track-id]");
    if (!a || !ready || e.ctrlKey || e.metaKey || e.shiftKey) return;
    e.preventDefault();
    play(TRACKS.find((t) => t.id === a.dataset.trackId));
  });

  playBtn.addEventListener("click", () => controller?.togglePlay());
  prevBtn.addEventListener("click", () => step(-1));
  nextBtn.addEventListener("click", () => step(1));
  for (const b of [shuffleBtn, repeatBtn]) {
    b.addEventListener("click", () => b.setAttribute("aria-pressed", String(b.getAttribute("aria-pressed") !== "true")));
  }
  seek.addEventListener("input", () => controller?.seek(seek.value / 1000));

  function onUpdate({ data }) {
    const { position, duration } = data;
    const playing = isPlaying(data);
    setPlaying(playing);
    clearTimeout(quiet);
    if (playing) quiet = setTimeout(() => setPlaying(false), 3000);
    seek.max = duration;
    seek.value = position;
    seek.style.setProperty("--pos", duration ? `${(position / duration) * 100}%` : "0%");
    timeNow.textContent = formatTime(position);
    timeEnd.textContent = formatTime(duration);
    if (current) onNow?.({ track: current, position, duration });
    if (position < duration - 1000) ended = false;
    if (!ended && duration > 0 && position >= duration - 250) {
      ended = true;
      if (repeatBtn.getAttribute("aria-pressed") === "true") play(current);
      else step(1);
    }
  }

  function mount() {
    if (ready || host.dataset.mounting) return;
    host.dataset.mounting = "1";
    window.onSpotifyIframeApiReady = (api) => {
      if (controller || host.querySelector("iframe")) return; // a retried load must not add a second player
      const el = document.createElement("div");
      host.append(el);
      api.createController(el, { uri: `spotify:playlist:${PLAYLIST_ID}`, width: "100%", height: 152 }, (c) => {
        controller = c;
        c.addListener("ready", () => { if (playOnLoad) { playOnLoad = false; c.play(); } });
        c.addListener("playback_update", onUpdate);
        if (wanted) { play(wanted); wanted = null; }
      });
    };
    const script = document.createElement("script");
    script.src = IFRAME_API;
    script.async = true;
    script.onload = () => { ready = true; };
    script.onerror = () => { delete host.dataset.mounting; }; // offline or blocked: links keep opening Spotify
    document.head.append(script);
  }

  function pause() {
    wanted = null; // a song asked for just before closing must not start unseen later
    playOnLoad = false;
    controller?.pause();
  }

  return { mount, pause };
}
